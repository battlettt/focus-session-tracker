"""Build demo/index.html: a static, offline walkthrough of the CLI.

Every output shown on the page is produced by running the real CLI
(focus_session_tracker.cli.main) against a temporary data file with a fake
clock, so the demo's numbers are the CLI's numbers. tests/test_demo.py fails
if demo/index.html is out of date.

Usage: python3 scripts/build_demo.py
"""

import html
import io
import os
import sys
import tempfile
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from focus_session_tracker import cli  # noqa: E402

OUTPUT = ROOT / "demo" / "index.html"
TZ = timezone(timedelta(hours=1))

# (caption, minutes since the previous step, command) for the first, narrated session.
FIRST_SESSION = [
    ("Mon 26 Oct 2026, 09:00", 0, ["start", "Write project report"]),
    ("", 18, ["distract", "email notification"]),
    ("", 7, ["pause"]),
    ("", 10, ["resume"]),
    ("", 15, ["status"]),
    ("", 20, ["stop"]),
    ("A few minutes later", 3, ["distract", "--last", "remembered a call to make"]),
]

# The rest of the sample week, run quietly: (day, hh, mm, task, minutes, distractions).
REST_OF_WEEK = [
    (26, 14, 0, "Code review", 25, ["phone"]),
    (27, 9, 30, "Write project report", 55, ["email notification"]),
    (28, 8, 45, "Study Spanish", 30, []),
    (28, 16, 0, "Code review", 40, ["phone", "chat message"]),
    (30, 10, 0, "Write project report", 70, ["email notification"]),
    (30, 19, 30, "Reading", 35, ["phone"]),
]

CLOSING = [
    ("Sun 1 Nov 2026, evening", ["history"]),
    ("", ["history", "--task", "report", "--details"]),
    ("", ["week"]),
]


class Runner:
    def __init__(self, path):
        self.path = path
        self.now = None

    def run(self, argv):
        out, err = io.StringIO(), io.StringIO()
        code = cli.main(["--data", self.path, *argv], clock=lambda: self.now, out=out, err=err)
        if code != 0:
            raise RuntimeError(f"demo command failed: {argv}: {err.getvalue()}")
        return out.getvalue().rstrip("\n")


def walkthrough():
    """Run the sample week and return [(caption, command, output)] for display."""
    folder = tempfile.mkdtemp(prefix="focus-demo-")
    runner = Runner(os.path.join(folder, "sessions.json"))
    steps = []
    runner.now = datetime(2026, 10, 26, 9, 0, tzinfo=TZ)
    for caption, minutes, argv in FIRST_SESSION:
        runner.now += timedelta(minutes=minutes)
        steps.append((caption, argv, runner.run(argv)))

    for day, hour, minute, task, length, notes in REST_OF_WEEK:
        runner.now = datetime(2026, 10, day, hour, minute, tzinfo=TZ)
        runner.run(["start", task])
        for i, note in enumerate(notes, 1):
            runner.now += timedelta(minutes=length * i // (len(notes) + 1))
            runner.run(["distract", note])
        runner.now = datetime(2026, 10, day, hour, minute, tzinfo=TZ) + timedelta(minutes=length)
        runner.run(["stop"])

    runner.now = datetime(2026, 11, 1, 20, 0, tzinfo=TZ)
    for caption, argv in CLOSING:
        steps.append((caption, argv, runner.run(argv)))
    return steps


def shell_quote(arg):
    return f'"{arg}"' if " " in arg else arg


PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Focus Session Tracker - sample walkthrough</title>
<style>
  body {{ font-family: system-ui, sans-serif; max-width: 52rem; margin: 2rem auto;
         padding: 0 1rem; color: #222; background: #fafaf8; line-height: 1.5; }}
  h1 {{ font-size: 1.5rem; margin-bottom: 0.25rem; }}
  .lede {{ color: #555; margin-top: 0; }}
  .gap {{ color: #555; font-style: italic; margin: 1.5rem 0 0.5rem; }}
  .caption {{ font-weight: 600; margin: 1.5rem 0 0.25rem; }}
  pre {{ background: #fff; border: 1px solid #ddd; border-radius: 6px; padding: 0.75rem 1rem;
         overflow-x: auto; margin: 0 0 0.75rem; font-size: 0.9rem; }}
  .cmd {{ color: #2a5d8f; }}
  footer {{ color: #666; font-size: 0.85rem; margin-top: 2rem; }}
</style>
</head>
<body>
<h1>Focus Session Tracker</h1>
<p class="lede">A sample week, shown as terminal commands and their output.
Everything below was produced by the real command line tool running on sample data
with a simulated clock. Data stays local; there are no streaks or scores.</p>
{body}
<footer>Generated by scripts/build_demo.py from the CLI's own output. Runs fully offline.</footer>
</body>
</html>
"""


def render(steps):
    parts = []
    for index, (caption, argv, output) in enumerate(steps):
        if index == len(FIRST_SESSION):
            parts.append('<p class="gap">The rest of the week: six more sessions on '
                         "Monday, Tuesday, Wednesday and Friday. Thursday and the weekend have none.</p>")
        if caption:
            parts.append(f'<p class="caption">{html.escape(caption)}</p>')
        command = "focus " + " ".join(shell_quote(a) for a in argv)
        parts.append(f'<pre><span class="cmd">$ {html.escape(command)}</span>\n'
                     f"{html.escape(output)}</pre>")
    return PAGE.format(body="\n".join(parts))


def build():
    return render(walkthrough())


if __name__ == "__main__":
    OUTPUT.write_text(build(), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
